export function findClassicPresetById(id: string): ClassicPreset | undefined {
  const resolved = resolveClassicPresetId(id);
  return CLASSIC_50_PRESETS.find((p) => p.id === resolved);
}

export function findClassicPresetByFormula(
  formula: string,
): ClassicPreset | undefined {
  try {
    return classicPresetsByCanonicalFormula.get(compileFormula(formula).formula);
  } catch {
    return undefined;
  }
}

const classicPresetsByCanonicalFormula = new Map(
  CLASSIC_50_PRESETS.map((preset) => [compileFormula(preset.formula).formula, preset]),
);

export function searchClassicPresets(
  query = "",
  category: ClassicPresetCategory | "ALL" = "ALL",
): readonly ClassicPreset[] {
  const normalizedCategory = category || "ALL";
  const q = query.trim().toLowerCase();
  return CLASSIC_50_PRESETS.filter((preset) => {
    if (
      normalizedCategory !== "ALL" &&
      preset.category !== normalizedCategory
    ) {
      return false;
    }
    if (!q) return true;
    const haystack = [
      preset.rankCode,
      `#${preset.rankCode}`,
      preset.label,
      preset.shortDescription,
      preset.category,
      preset.ruleType,
      preset.signalBias,
      preset.formula,
      ...preset.prerequisites,
      ...preset.synonyms,
    ]
      .join(" ")
      .toLowerCase();
    return q.split(/\s+/).every((token) => haystack.includes(token));
  });
}
